#include <stdio.h>
#include <thylacine/loom_service_fids.h>
#include <thylacine/errno.h>
#define CHECK(x,msg) do { if(!(x)){fprintf(stderr,"FAIL %s\n",msg);return 1;}++checks;}while(0)
static struct loom_slot_table slots;
static struct loom_service_node_table nodes;
int main(void) {
 unsigned checks=0;
 struct loom_service_ref root={0},other={0},a={0},b={0},old={0},zero={0};
 u32 wire=999;
 CHECK(!loom_service_node_prepare(&slots,&nodes,LOOM_SERVICE_SCOPE,zero,&root),"root reserve");
 CHECK(!loom_service_node_publish(&slots,&nodes,root),"root publish");
 nodes.nodes[root.slot].state=LOOM_SERVICE_READY;
 CHECK(!loom_slot_pin(&slots,root,LOOM_SERVICE_SCOPE),"root protocol pin");
 CHECK(loom_fid_bind_root(&slots,&nodes,root,UINT32_MAX)==-T_E_INVAL,"NOFID root denied");
 CHECK(!loom_fid_bind_root(&slots,&nodes,root,0),"root mapping");
 CHECK(loom_fid_bind_root(&slots,&nodes,root,0)==-T_E_BUSY,"duplicate root bind");
 CHECK(!loom_service_node_prepare(&slots,&nodes,LOOM_SERVICE_SCOPE,zero,&other),"other reserve");
 CHECK(!loom_service_node_publish(&slots,&nodes,other),"other publish");
 nodes.nodes[other.slot].state=LOOM_SERVICE_READY;
 CHECK(!loom_slot_pin(&slots,other,LOOM_SERVICE_SCOPE),"other protocol pin");
 CHECK(!loom_fid_bind_root(&slots,&nodes,other,0),"wire numbers scoped");
 CHECK(!loom_service_node_prepare(&slots,&nodes,LOOM_SERVICE_FID,root,&a),"child reserve");
 CHECK(!loom_service_node_publish(&slots,&nodes,a),"child publish");
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,0,&wire)==-T_E_NOENT && wire==999,"unbound source denied");
 CHECK(loom_fid_claim_walk(&slots,&nodes,a,root,0)==-T_E_INVAL,"zero request denied");
 CHECK(loom_fid_claim_walk(&slots,&nodes,a,other,1)==-T_E_CANCELED,"wrong parent claim denied");
 slots.slots[a.slot].pins=UINT32_MAX;
 CHECK(loom_fid_claim_walk(&slots,&nodes,a,root,1)==-T_E_NOSPC && !nodes.nodes[a.slot].fid_claim,"claim saturation unchanged");
 slots.slots[a.slot].pins=0;
 CHECK(!loom_fid_claim_walk(&slots,&nodes,a,root,1),"walk claim");
 CHECK(loom_fid_claim_walk(&slots,&nodes,a,root,2)==-T_E_BUSY,"duplicate walk excluded");
 old=a;old.incarnation+=((u64)1<<32);
 CHECK(loom_fid_commit_walk(&slots,&nodes,old,root,1,1)==-T_E_NOENT,"full incarnation commit required");
 old=a;old.reserved=1;
 CHECK(loom_fid_commit_walk(&slots,&nodes,old,root,1,1)==-T_E_NOENT,"reserved commit ref denied");
 CHECK(loom_fid_commit_walk(&slots,&nodes,a,root,2,1)==-T_E_BUSY,"wrong owner cannot publish");
 CHECK(loom_fid_commit_walk(&slots,&nodes,a,root,1,UINT32_MAX)==-T_E_INVAL,"NOFID denied");
 CHECK(loom_fid_commit_walk(&slots,&nodes,a,root,1,0)==-T_E_BUSY,"root alias denied");
 nodes.nodes[root.slot].state=LOOM_SERVICE_ABORTING;
 CHECK(loom_fid_commit_walk(&slots,&nodes,a,root,1,1)==-T_E_CANCELED,"abort beats walk commit");
 nodes.nodes[root.slot].state=LOOM_SERVICE_READY;
 CHECK(!loom_fid_commit_walk(&slots,&nodes,a,root,1,1),"walk commit");
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,0,&wire)==-T_E_BUSY,"publication retains physical claim");
 CHECK(loom_fid_release_claim(&slots,&nodes,a,2)==-T_E_BUSY,"wrong owner cannot drop");
 CHECK(!loom_fid_release_claim(&slots,&nodes,a,1) && slots.slots[a.slot].pins==0,"walk physical release");
 CHECK(loom_fid_release_claim(&slots,&nodes,a,1)==-T_E_BUSY,"double claim drop denied");
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,LFID_READ,&wire)==-T_E_ACCES && wire==999,"unopened data denied");
 old=a;old.incarnation+=((u64)1<<32);
 CHECK(loom_fid_borrow(&slots,&nodes,old,root,0,&wire)==-T_E_NOENT,"full incarnation required");
 old=a;old.reserved=1;
 CHECK(loom_fid_borrow(&slots,&nodes,old,root,0,&wire)==-T_E_NOENT,"reserved ref denied");
 CHECK(loom_fid_borrow(&slots,&nodes,a,other,0,&wire)==-T_E_CANCELED,"wrong parent borrow denied");
 nodes.nodes[a.slot].fid_borrows=UINT32_MAX;
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,0,&wire)==-T_E_NOSPC && wire==999 && !slots.slots[a.slot].pins,"borrow saturation unchanged");
 nodes.nodes[a.slot].fid_borrows=0;
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,4,&wire)==-T_E_INVAL && wire==999,"unknown access denied");
 CHECK(!loom_fid_borrow(&slots,&nodes,a,root,0,&wire) && wire==1 && nodes.nodes[a.slot].fid_borrows==1,"metadata borrow tracked");
 CHECK(loom_fid_claim_open(&slots,&nodes,a,root,3)==-T_E_BUSY,"open waits for source borrowers");
 CHECK(!loom_fid_put(&slots,&nodes,a) && nodes.nodes[a.slot].fid_borrows==0 && slots.slots[a.slot].pins==0,"borrow release exact");
 CHECK(loom_fid_put(&slots,&nodes,a)==-T_E_INVAL,"double borrow put denied");
 CHECK(!loom_fid_claim_open(&slots,&nodes,a,root,3),"exclusive open claim");
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,0,&wire)==-T_E_BUSY,"open excludes concurrent borrow");
 CHECK(loom_fid_commit_open(&slots,&nodes,a,root,4,0)==-T_E_BUSY,"open exact owner");
 CHECK(loom_fid_commit_open(&slots,&nodes,a,root,3,3)==-T_E_INVAL,"open mode bounded");
 CHECK(!loom_fid_commit_open(&slots,&nodes,a,root,3,0),"open read commit");
 CHECK(!loom_fid_release_claim(&slots,&nodes,a,3),"open physical release");
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,LFID_WRITE,&wire)==-T_E_ACCES,"write permission retained");
 CHECK(!loom_fid_borrow(&slots,&nodes,a,root,LFID_READ,&wire),"read allowed");
 CHECK(!loom_fid_put(&slots,&nodes,a),"read put");
 CHECK(loom_fid_claim_open(&slots,&nodes,a,root,4)==-T_E_NOENT,"second open denied");
 // Root has a protocol pin and child parent pins. They are not FID borrows.
 CHECK(slots.slots[root.slot].pins==2,"root lifetime pins distinct");
 CHECK(!loom_fid_claim_open(&slots,&nodes,root,root,5),"root open with child pins");
 CHECK(!loom_fid_commit_open(&slots,&nodes,root,root,5,2),"root readwrite commit");
 CHECK(!loom_fid_release_claim(&slots,&nodes,root,5) && slots.slots[root.slot].pins==2,"root claim preserves lifetime pins");
 CHECK(!loom_fid_borrow(&slots,&nodes,root,root,3,&wire) && wire==0,"root readwrite borrow");
 CHECK(!loom_fid_put(&slots,&nodes,root) && slots.slots[root.slot].pins==2,"root put preserves lifetime pins");
 CHECK(loom_fid_begin_clunk(&slots,&nodes,root,root,6)==-T_E_NOENT,"root clunk denied");
 CHECK(!loom_fid_borrow(&slots,&nodes,a,root,LFID_READ,&wire),"hold prior reader");
 CHECK(!loom_fid_begin_clunk(&slots,&nodes,a,root,6) && slots.slots[a.slot].phase==LSLOT_RETIRING,"clunk closes admission with reader");
 CHECK(loom_fid_borrow(&slots,&nodes,a,root,LFID_READ,&wire)==-T_E_NOENT,"clunk blocks new reader");
 CHECK(loom_fid_finish_clunk(&slots,&nodes,a,6)==-T_E_BUSY,"clunk waits for prior reader");
 CHECK(loom_fid_release_claim(&slots,&nodes,a,6)==-T_E_BUSY,"clunk owner held until quiescent");
 CHECK(!loom_fid_put(&slots,&nodes,a),"retiring reader put");
 CHECK(loom_fid_clunk_wire(&slots,&nodes,a,7,&wire)==-T_E_BUSY,"clunk exact owner");
 CHECK(!loom_fid_clunk_wire(&slots,&nodes,a,6,&wire) && wire==1,"clunk wire after drain");
 CHECK(!loom_fid_finish_clunk(&slots,&nodes,a,6),"clunk quiescent finish");
 CHECK(loom_fid_reap(&slots,&nodes,a)==-T_E_BUSY,"physical claim blocks reap");
 CHECK(!loom_service_node_prepare(&slots,&nodes,LOOM_SERVICE_FID,root,&b),"second child reserve");
 CHECK(!loom_service_node_publish(&slots,&nodes,b),"second child publish");
 CHECK(!loom_fid_claim_walk(&slots,&nodes,b,root,8),"second walk claim");
 CHECK(loom_fid_commit_walk(&slots,&nodes,b,root,8,1)==-T_E_BUSY,"retiring wire alias denied");
 CHECK(!loom_fid_commit_walk(&slots,&nodes,b,root,8,2),"second walk commit");
 CHECK(!loom_fid_release_claim(&slots,&nodes,b,8),"second walk release");
 CHECK(!loom_fid_release_claim(&slots,&nodes,a,6),"clunk physical release");
 old=a;
 CHECK(!loom_fid_reap(&slots,&nodes,a) && slots.slots[root.slot].pins==2 && !nodes.nodes[a.slot].fid_flags,"reap drops parent and mapping");
 CHECK(!loom_service_node_prepare(&slots,&nodes,LOOM_SERVICE_FID,root,&a),"replacement reserve");
 CHECK(!loom_service_node_publish(&slots,&nodes,a) && a.incarnation!=old.incarnation,"replacement publish");
 CHECK(loom_fid_reap(&slots,&nodes,old)==-T_E_NOENT && slots.slots[root.slot].pins==3,"stale reap preserves replacement");
 CHECK(loom_fid_retire_aborted(&slots,&nodes,b)==-T_E_BUSY,"ready parent forbids abort retirement");
 CHECK(!loom_fid_claim_open(&slots,&nodes,b,root,9),"abort open claim");
 nodes.nodes[root.slot].state=LOOM_SERVICE_ABORTING;
 CHECK(loom_fid_commit_open(&slots,&nodes,b,root,9,1)==-T_E_CANCELED,"abort beats open commit");
 CHECK(loom_fid_retire_aborted(&slots,&nodes,b)==-T_E_BUSY,"abort waits for physical claim");
 CHECK(!loom_fid_release_claim(&slots,&nodes,b,9),"aborted open release");
 // Artificial READY here creates a separate simulated interleaving: no protocol
 // success is asserted by this sequential helper fixture.
 nodes.nodes[root.slot].state=LOOM_SERVICE_READY;
 CHECK(!loom_fid_borrow(&slots,&nodes,b,root,0,&wire),"abort prior borrower");
 nodes.nodes[root.slot].state=LOOM_SERVICE_ABORTING;
 CHECK(loom_fid_retire_aborted(&slots,&nodes,b)==-T_E_BUSY,"abort waits for source borrower");
 loom_slots_close(&slots);
 CHECK(!loom_fid_put(&slots,&nodes,b),"closed source put");

 CHECK(!loom_fid_retire_aborted(&slots,&nodes,b),"aborted mapped fid retires locally");
 CHECK(!loom_fid_reap(&slots,&nodes,b),"closed mapped fid reap");
 CHECK(!loom_fid_retire_aborted(&slots,&nodes,a),"aborted unused fid retires locally");
 CHECK(!loom_fid_reap(&slots,&nodes,a) && slots.slots[root.slot].pins==1,"closed children drop parent pins");
 printf("PASS fid mapping: %u checks, node=%zu table=%zu\n",checks,sizeof(struct loom_service_node),sizeof(nodes));
 return 0;
}
