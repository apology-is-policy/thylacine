#!/usr/bin/env python3
"""Bake trusted Lex curiata type from repository-owned fonts (fonttools only).

Run manually when changing the type specification. Normal OS builds consume
the committed alpha masks, never a font parser or user-selected font. Uses the
same nonzero-winding, 4x supersampling rasterizer as Cornucopia.
"""
import importlib.util
import math
from pathlib import Path
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("cornucopia_bake", ROOT / "tools/bake-cornucopia.py")
bake = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bake)
CHARS = list(range(32, 127)) + [0xb7, 0x2014]
SANS = "third_party/ibm-plex/ttf/IBMPlexSans-Regular.ttf"
TITLE = "third_party/ibm-plex/ttf/IBMPlexSans-Medium.ttf"
MONO = "usr/lib/cornucopia/src/cornucopia-subset.ttf"
FACES = [("Label", SANS, 12), ("Body", SANS, 14), ("Section", TITLE, 15),
         ("Identity", SANS, 18), ("Title", TITLE, 29),
         ("SmallMono", MONO, 10), ("Rail", MONO, 11), ("Mono", MONO, 14)]

# The scales the type is baked at: pixels to a layout pixel. The layout is the
# same at each (the box, the baseline, the bearing room and the advance are the
# 1x ones, times the scale); only the outline is drawn finer.
SCALES = (1, 2)

def main():
    sets = {k: bytearray() for k in SCALES}
    records = []
    for name, path, size in FACES:
        font = TTFont(ROOT / path)
        cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
        scale = size / font["head"].unitsPerEm
        # Two pixels of horizontal bearing room; a fixed line box per face.
        baseline = math.ceil(size * 1.05)
        height = math.ceil(size * 1.4)
        width = math.ceil(max(font["hmtx"][cmap[c]][0] for c in CHARS) * scale) + 4
        offsets = [len(sets[k]) for k in SCALES]
        for cp in CHARS:
            glyph = cmap[cp]
            advance = round(font["hmtx"][glyph][0] * scale)
            for k in SCALES:
                ss = k * bake.SS
                pen = bake.FlattenPen(glyphs, scale * ss, baseline * ss)
                glyphs[glyph].draw(pen)
                if pen.cur:
                    pen.contours.append(pen.cur)
                contours = [[(x + 2 * ss, y) for x, y in contour] for contour in pen.contours]
                grid = bake.rasterize(contours, width * ss, height * ss)
                sets[k].append(advance)
                sets[k].extend(bake.downsample(grid, width * ss, height * ss, width * k, height * k))
        records.append(f"    Font::{name} => ([{', '.join(str(o) for o in offsets)}], {width}, {height}),")
    out = ROOT / "usr/lictor/src"
    for k in SCALES:
        (out / ("type.bin" if k == 1 else f"type{k}.bin")).write_bytes(sets[k])
    (out / "type_metrics.rs").write_text(
        "// Generated by tools/bake-lictor.py; do not edit.\n"
        f"pub const SCALES: usize = {len(SCALES)};\n"
        "fn metrics(font: Font) -> ([usize; SCALES], usize, usize) { match font {\n"
        + "\n".join(records) + "\n} }\n")
    print(f"Baked {len(FACES)} faces, {len(CHARS)} glyphs each, at {SCALES}: "
          + ", ".join(f"{len(sets[k])} bytes" for k in SCALES))

if __name__ == "__main__":
    main()
