/// Whether fd 2 was open when haul STARTED. Decided once, before haul opens
/// anything: with slot 2 empty, the kernel hands haul's own files out from the
/// lowest free slot, so a later look at "fd 2" can find the token file or the
/// TCP data file -- and a diagnostic written there would go into the 9P stream.
static STDERR_LIVE: AtomicBool = AtomicBool::new(false);

/// One line for the operator, on stderr, where the terminal that ran haul
/// shows it. `t_putstr` (SYS_PUTS) writes the KERNEL console instead: the same
/// device as stderr on the serial console, and a different one in a Halcyon
/// tile, where every haul line -- errors included -- used to land on serial and
/// the tile showed nothing. The console is only the fallback, for the park form
/// under a launcher that gave it no stderr.
fn tell(line: &str) {
    if STDERR_LIVE.load(Ordering::Relaxed) {
        use libthyla_rs::io::Write;
        if libthyla_rs::io::stderr().write_all(line.as_bytes()).is_ok() {
            return;
        }
    }
    let _ = t_putstr(line);
}

macro_rules! say {
    ($($a:tt)*) => {{
        let mut s = alloc::format!($($a)*);
        s.push('\n');
        tell(&s);
    }};
}

/// Progress, under `-v`.
///
/// Not debug scaffolding: every step below can BLOCK -- the dial, the
/// handshake's two reads, and the attach (which drives Tversion + Tattach
/// synchronously inside the syscall). A haul that is merely slow and a haul
/// that is wedged look identical without this, which is exactly the state the
/// first guest run left us in: ninety seconds of silence and no way to say
/// which syscall owned them.
static VERBOSE: AtomicU32 = AtomicU32::new(0);

macro_rules! step {
    ($($a:tt)*) => {{
        if VERBOSE.load(Ordering::Relaxed) != 0 {
            let mut s = alloc::string::String::from("haul: .. ");
            s.push_str(&alloc::format!($($a)*));
            s.push('\n');
            tell(&s);
        }
    }};
}

/// The largest 9P message haul will relay in either direction.
///
/// A 9P message is `size[4]` INCLUDING those four bytes, so this bounds the
/// whole frame. It is a shim-side ceiling, not the negotiated msize: haul does
/// not parse Tversion (it is a transport, not a client), so it cannot know what
/// the two ends agreed on.
///
/// The number is chosen against what the two ends CAN agree on. This transport
/// is the pipe attach, whose msize is the fixed `SYS_ATTACH_DEFAULT_MSIZE`
/// (4 KiB, kernel/syscall.c) -- the kernel proposes it, caps its own recv at it,
/// and there is no path by which a larger frame is legitimate here. 64 KiB
/// therefore leaves sixteen-fold headroom for a future msize bump while keeping
/// the worst case a hostile server can drive to two 64 KiB buffers, one per
/// pump, against `INITIAL_HEAP_SIZE` (4 MiB, and NOT growable).
///
/// It was 1 MiB, which was described as "far below a length a hostile peer could
/// use to make us allocate the heap". Two of those is a quarter of the heap, and
/// on exhaustion the panic handler calls `t_exits(1)` -- so a bound written to
/// prevent a denial of service was set where it could deliver one.
const MSG_MAX: u32 = 64 * 1024;

/// A 9P message is at minimum `size[4] type[1] tag[2]`. npxf's server refuses
/// anything shorter as a runt; matching it here means a malformed frame dies at
/// the transport instead of being handed to a parser on either side.
const MSG_MIN: u32 = 7;

/// Per-pump stack. One page is ample -- a pump's frame is a buffer pointer and
/// a few counters; the message buffer itself is heap.
const PUMP_STACK: u64 = 64 * 1024;

/// Set by whichever pump stops first, so the survivor's diagnosis names the
/// side that actually ended rather than the side that noticed, and so the main
/// thread learns the transport is over.
static STOPPED: AtomicU32 = AtomicU32::new(0);

const STOP_NONE: u32 = 0;
const STOP_UP: u32 = 1; // kernel -> server direction ended
const STOP_DOWN: u32 = 2; // server -> kernel direction ended

/// Read exactly `buf.len()` bytes, or report short. A single `read` on either a
/// pipe or a TCP stream may return less than asked for, and a 9P frame that is
/// split across two reads is the ordinary case, not the exceptional one.
fn read_exact(fd: i64, buf: &mut [u8]) -> bool {
    let mut off = 0usize;
    while off < buf.len() {
        let n = unsafe { libthyla_rs::t_read(fd, buf[off..].as_mut_ptr(), buf.len() - off) };
        if n <= 0 {
            return false; // EOF or error: the caller treats both as "channel over"
        }
        off += n as usize;
    }
    true
}

/// How long the handshake will wait for the server's flight, matching the
/// bracket npxf puts around its own (`kHandshakeTimeoutMs`, channel.hpp).
///
/// Without it, a peer that completes the TCP handshake and then says nothing
/// holds haul in a read forever, BEFORE authentication -- so anything that can
/// accept a connection can pin the process, with no token and no reply. The
/// verbose trace stops at "sent flight 1", which is a good description of the
/// symptom and no help at all against it.
const HANDSHAKE_MS: i32 = 15_000;

/// How long a stalled write waits for the far side to make room before the
/// channel is declared dead. A healthy TCP transmit buffer drains in
/// milliseconds; a socket that is actually gone never becomes writable at all,
/// so the only thing this bound has to separate is "slow" from "never" -- and
/// erring long is right, because a stalled remote filesystem should block, not
/// tear the mount down.
const WRITE_STALL_MS: i32 = 30_000;

/// THE READINESS FD IS NOT THE DATA FD, and using the wrong one is silent.
///
/// A netd connection is two files. `data` carries bytes; `ready` carries
/// readiness, and only `ready` is marked QTPOLL (`usr/netd/src/server.rs`
/// `P9_QTFILE | P9_QTPOLL` -- the `data` file is not). `dev9p_poll`'s QTPOLL
/// gate deliberately FAILS SAFE for everything else: an unmarked file is
/// "POSIX always-ready", returning the requested bits immediately rather than
/// probing (`kernel/dev9p_poll.c`).
///
/// So polling the DATA fd does not fail -- it succeeds, instantly, always, and
/// says nothing. A POLLOUT wait on it becomes a busy spin; a POLLIN wait before
/// a blocking read becomes a no-op that leaves the read unbounded. Both are
/// bugs that look exactly like working code, which is why this type exists
/// instead of an `i64` parameter that either fd would satisfy.
///
/// `Ready(fd) == the fd to poll`; for a pipe that is the pipe itself, whose
/// POLLOUT is real (`kernel/pipe.c` sets it on `count < PIPE_BUF_SIZE`).
#[derive(Copy, Clone)]
struct Ready(i64);

/// Wait for `events` on a readiness fd, up to `ms`. False on timeout or error.
fn wait_ready(r: Ready, events: i16, ms: i32) -> bool {
    let mut pfd = libthyla_rs::TPollFd { fd: r.0 as i32, events, revents: 0 };
    let n = unsafe { libthyla_rs::t_poll(&mut pfd, 1, ms) };
    n > 0 && pfd.revents & events != 0
}

/// `read_exact` under a TOTAL deadline, for the pre-authentication window where
/// a silent peer must not be able to park us.
///
/// The bound is for the whole read, not for each wait. A per-wait bound was the
/// first shape here, defended with "the flights are 64 bytes, so there is
/// nothing to dribble" -- and 64 bytes is exactly 64 dribbles: one byte every
/// 14 seconds would have stretched a 15-second bracket to sixteen minutes, per
/// connection, before authentication. A peer that is making progress is not
/// thereby entitled to unlimited time.
fn read_exact_before(fd: i64, r: Ready, buf: &mut [u8], ms: i32) -> bool {
    let started = libthyla_rs::time::Instant::now();
    let mut off = 0usize;
    while off < buf.len() {
        let spent = started.elapsed().as_millis() as i64;
        let left = ms as i64 - spent;
        if left <= 0 {
            return false;
        }
        if !wait_ready(r, libthyla_rs::T_POLLIN, left as i32) {
            return false;
        }
        let n = unsafe { libthyla_rs::t_read(fd, buf[off..].as_mut_ptr(), buf.len() - off) };
        if n <= 0 {
            return false;
        }
        off += n as usize;
    }
    true
}

/// Write all of `buf`, treating a zero-byte write as back-pressure rather than
/// as failure.
///
/// A /net data fd does NOT block. netd's TCP send is
/// `send_slice(data).unwrap_or(0)` (usr/netd/src/server.rs), and dev9p hands
/// that count straight back to EL0 (`dev9p_write` returns `accepted`,
/// kernel/dev9p.c), so a full transmit buffer makes `t_write` return 0 with the
/// connection perfectly healthy. The obvious `n <= 0` idiom reads that as the
/// end of the channel and tears the mount down under nothing worse than a busy
/// link -- and can do it MID-RECORD, leaving a truncated AEAD frame on the wire
/// for the peer to reject.
///
/// The zero is ambiguous on its own: `unwrap_or(0)` swallows the error a dead
/// socket returns too, so the count alone cannot separate "full" from "gone".
/// Readiness can -- but only the RIGHT fd's. POLLOUT on the `ready` sibling is
/// netd's `can_send()`, which is false for a dead socket and true once the send
/// window has room; POLLOUT on `data` is the always-ready answer of a file that
/// carries no readiness at all. See `Ready`.
fn write_exact(fd: i64, r: Ready, buf: &[u8]) -> bool {
    let mut off = 0usize;
    // Bounds the CUMULATIVE time spent making no progress, reset by any byte
    // written. A per-wait bound would not terminate if readiness kept firing
    // while the write kept returning 0 -- POLLOUT is netd's `can_send()`
    // sampled at poll time, and a window that opens and closes again between
    // the poll and the write is a spurious wakeup, not a contract violation.
    // Without this the loop would be bounded only by the peer's good behaviour.
    let mut stalled_since: Option<libthyla_rs::time::Instant> = None;
    while off < buf.len() {
        let n = unsafe { libthyla_rs::t_write(fd, buf[off..].as_ptr(), buf.len() - off) };
        if n < 0 {
            return false;
        }
        if n == 0 {
            let since = *stalled_since.get_or_insert_with(libthyla_rs::time::Instant::now);
            let spent = since.elapsed().as_millis() as i64;
            let left = WRITE_STALL_MS as i64 - spent;
            if left <= 0 || !wait_ready(r, libthyla_rs::T_POLLOUT, left as i32) {
                say!("haul: write stalled with {} bytes left", buf.len() - off);
                return false;
            }
            continue;
        }
        stalled_since = None;
        off += n as usize;
    }
    true
}

/// Decode the 9P `size[4]` little-endian prefix and validate it.
///
/// Returns the TOTAL frame length (header included), or None if the peer
/// claimed a size that cannot be a 9P message. Refusing here is what keeps a
/// bad length from becoming a giant allocation or an inward-handed lie.
fn frame_len(hdr: &[u8; 4]) -> Option<u32> {
    let size = u32::from_le_bytes(*hdr);
    if !(MSG_MIN..=MSG_MAX).contains(&size) {
        return None;
    }
    Some(size)
}

/// Read one complete 9P message from `src` into `buf` (header included).
///
/// Returns false at end of channel or on a length the peer had no business
/// claiming. Refusing the length HERE is what stops it becoming a giant
/// allocation or a lie handed to the next layer.
fn read_frame(src: i64, buf: &mut Vec<u8>) -> bool {
    let mut hdr = [0u8; 4];
    if !read_exact(src, &mut hdr) {
        return false;
    }
    let size = match frame_len(&hdr) {
        Some(s) => s,
        None => {
            say!(
                "haul: refusing a frame claiming {} bytes (bound {})",
                u32::from_le_bytes(hdr),
                MSG_MAX
            );
            return false;
        }
    };
    buf.clear();
    buf.extend_from_slice(&hdr);
    buf.resize(size as usize, 0);
    read_exact(src, &mut buf[4..])
}

/// Everything the kernel->server pump needs. Passed by pointer through
/// `spawn_raw`'s argument rather than through statics: the Sealer is owned by
/// exactly one thread, and a static would have to be `static mut` to say so.
struct UpCtx {
    src: i64,
    dst: i64,
    /// Readiness for `dst`, which is the TCP connection -- so this is its
    /// `ready` sibling, never `dst` itself. See `Ready`.
    dst_ready: Ready,
    sealer: Option<npxf::Sealer>,
}

/// Everything the server->kernel pump needs.
struct DownCtx {
    src: i64,
    dst: i64,
    /// Readiness for `dst`, which is a pipe -- and a pipe's own fd carries real
    /// POLLOUT (`kernel/pipe.c`), so here it IS `dst`.
    dst_ready: Ready,
    opener: Option<npxf::Opener>,
    close_on_finish: bool, // pipe writer is private; a posted connection is shared
}

/// The kernel -> server pump ended: record it and exit the thread, closing
/// nothing. `finish_down` explains why this direction has nothing it may close.
fn finish_up() -> ! {
    let _ = STOPPED.compare_exchange(STOP_NONE, STOP_UP, Ordering::AcqRel, Ordering::Acquire);
    unsafe { libthyla_rs::t_thread_exit() };
}

/// The server -> kernel pump ended: record it, close the pipe end the kernel's
/// replies arrive through, and exit the thread.
///
/// THE CLOSE IS WHAT MAKES A DEAD SERVER AN ERROR RATHER THAN A HANG. The kernel
/// reads replies with no deadline (the Spoor transport's `set_recv_deadline` is
/// NULL), so while `s2c_wr` is open, a request whose reply can no longer come
/// waits forever. The main thread bounds that only from a loop that watches
/// STOPPED, and it is in no such loop while it sits inside a synchronous 9P
/// call -- `t_attach_9p`, or the `-v` listing. A server that hung up straight
/// after the handshake used to leave haul inside the attach for good. EOF on
/// `s2c_rd` is a transport break the kernel's 9P client latches as a dead
/// session, failing every waiter, so the call returns an error instead.
///
/// A PUMP MAY CLOSE ONLY AN FD NO OTHER THREAD CAN BE USING. The hazard is one
/// thread's close landing on another thread's in-flight use of the same fd,
/// whose number can be recycled in between. That is why neither pump may close
/// `tcp_fd`, the one fd they share, and why "whichever pump dies closes the
/// kernel's read side" is refused: the up pump would be closing THIS pump's fd.
/// `s2c_wr` has exactly one user, this thread -- the attach took its refs on the
/// CLIENT ends, main never touches it, and a spawned command inherits only its
/// stdio, which cannot be this fd: `run` refuses the command form unless fds 0-2
/// are already taken, so every fd haul opens lands above them. After the close
/// this thread exits without reading `ctx` again, so a recycled number is never
/// used under its old meaning. STOPPED is set first,
/// so by the time the kernel can see the EOF, main's diagnosis names this side.
///
/// The up pump's end, `c2s_rd`, is just as exclusive and still stays open.
/// Closing it would send the kernel's next write into the pipe's read-EOF arm,
/// which posts a `pipe` note to whichever Proc issued that 9P call
/// (`kernel/pipe.c`, the CNBFRAME branch): a transport event delivered as that
/// Proc's own write on a closed pipe. Nor is it needed, because a call is stuck
/// only while its REPLY direction is. Inside main's synchronous calls, every way
/// the up pump can end either follows the kernel's own teardown (EOF on
/// `c2s_rd`), cannot happen with the kernel's frames (a refused length, a payload
/// over MSG_MAX, a spent record counter), or comes with netd or the connection
/// gone -- which ends this pump's read too, since netd reports a closed socket
/// as EOF. The one death it can have alone, a write stalled for WRITE_STALL_MS
/// against a live peer that stopped reading, needs a full TCP send buffer
/// (netd's is 64 KiB), and those calls send a few hundred bytes. Outside them,
/// main watches STOPPED.
fn finish_down(ctx: &DownCtx) -> ! {
    let _ = STOPPED.compare_exchange(STOP_NONE, STOP_DOWN, Ordering::AcqRel, Ordering::Acquire);
    if ctx.close_on_finish { let _ = unsafe { t_close(ctx.dst) }; }
    unsafe { libthyla_rs::t_thread_exit() };
}

/// kernel -> server. Reads T-messages the kernel wrote into its pipe and puts
/// them on the wire -- as-is when plain, or as one AEAD record each when the
/// channel is secured.
extern "C" fn pump_up(arg: u64) {
    mask_pipe_note();
    // SAFETY: `arg` is the leaked Box handed to spawn_raw below, and this
    // thread is its only reader for the rest of the process's life.
    let ctx = unsafe { &mut *(arg as *mut UpCtx) };
    let mut msg: Vec<u8> = Vec::new();
    let mut rec: Vec<u8> = Vec::new();

    while read_frame(ctx.src, &mut msg) {
        let ok = match ctx.sealer.as_mut() {
            None => write_exact(ctx.dst, ctx.dst_ready, &msg),
            Some(s) => match s.seal(&msg, &mut rec) {
                Ok(()) => write_exact(ctx.dst, ctx.dst_ready, &rec),
                Err(e) => {
                    say!("haul: sealing a {}-byte message failed ({:?})", msg.len(), e);
                    false
                }
            },
        };
        if !ok {
            break;
        }
    }
    finish_up();
}

/// server -> kernel. Takes R-messages off the wire and writes them into the
/// kernel's pipe, decrypting first when the channel is secured.
extern "C" fn pump_down(arg: u64) {
    mask_pipe_note();
    // SAFETY: as pump_up.
    let ctx = unsafe { &mut *(arg as *mut DownCtx) };
    let mut buf: Vec<u8> = Vec::new();

    loop {
        let ok = match ctx.opener.as_mut() {
            // Plain: the stream IS 9P, so the same framed relay as the other
            // direction.
            None => read_frame(ctx.src, &mut buf) && write_exact(ctx.dst, ctx.dst_ready, &buf),
            Some(o) => match read_record(ctx.src, o, &mut buf) {
                RecordIn::Message(n) => write_exact(ctx.dst, ctx.dst_ready, &buf[..n]),
                RecordIn::Ended => false,
            },
        };
        if !ok {
            break;
        }
    }
    finish_down(ctx);
}

enum RecordIn {
    /// `buf[..n]` holds one decrypted 9P message.
    Message(usize),
    /// Clean EOF, a refused length, or a failed tag -- all terminal.
    Ended,
}

/// Read one AEAD record and decrypt it in place.
///
/// The decrypted payload must be a whole 9P message whose own `size[4]` equals
/// the record's length -- npxf's server enforces exactly that on its side, and
/// we enforce it here because the kernel reads a BYTE STREAM: a payload whose
/// declared size disagreed with its length would silently desync the pipe
/// rather than fail.
fn read_record(src: i64, o: &mut npxf::Opener, buf: &mut Vec<u8>) -> RecordIn {
    let mut hdr = [0u8; npxf::RECORD_HDR];
    if !read_exact(src, &mut hdr) {
        return RecordIn::Ended;
    }
    let body = match o.body_len(&hdr) {
        Ok(n) => n,
        Err(e) => {
            say!(
                "haul: refusing a record claiming {} bytes ({:?})",
                u32::from_le_bytes(hdr),
                e
            );
            return RecordIn::Ended;
        }
    };

    buf.clear();
    buf.resize(body, 0);
    if !read_exact(src, buf) {
        return RecordIn::Ended;
    }

    let n = match o.open(&hdr, buf) {
        Ok(pt) => pt.len(),
        Err(e) => {
            // A tag failure is tampering, reordering or truncation. The session
            // is already poisoned by `open`; say so plainly and end.
            say!("haul: record authentication failed ({:?}) -- the channel is over", e);
            return RecordIn::Ended;
        }
    };

    if n < MSG_MIN as usize || u32::from_le_bytes([buf[0], buf[1], buf[2], buf[3]]) as usize != n {
        say!("haul: a record's 9P size field disagrees with the record length");
        return RecordIn::Ended;
    }
    RecordIn::Message(n)
}

/// A pump's writes to a closed pipe come back as EPIPE, never as the `pipe`
/// note's default death. libthyla-rs masks the note on the MAIN thread only (the
/// mask is per-thread and spawn_raw does not inherit it), and a pump writes
/// both pipes and, through `tell`, stderr -- which `ut` hands a command as a
/// pipe nobody reads when it has no console to give. Unmasked, one diagnostic
/// there would kill haul before its main thread could report on the console.
fn mask_pipe_note() {
    let _ = unsafe {
        libthyla_rs::t_note_mask(1u64 << libthyla_rs::T_NOTE_BIT_PIPE, core::ptr::null_mut())
    };
}

/// A pump context, bound to the one entry point allowed to receive it.
///
/// The binding is the whole point of the trait. `UpCtx` and `DownCtx` are
/// layout-identical -- two fds and an `Option` holding a key -- so handing
/// `pump_up` a `DownCtx` would compile, link and run, and would seal outgoing
/// records under the RECEIVE key. Nothing crashes; the peer simply rejects every
/// record, and the tag failure says nothing about why. Taking the entry point as
/// a separate argument made that swap a one-token edit away at both call sites;
/// making it an associated constant makes it unrepresentable.
trait Pump: Sized {
    const ENTRY: extern "C" fn(u64);
}

impl Pump for UpCtx {
    const ENTRY: extern "C" fn(u64) = pump_up;
}

impl Pump for DownCtx {
    const ENTRY: extern "C" fn(u64) = pump_down;
}

/// Spawn one pump, handing it ownership of `ctx`.
///
/// The Box is leaked deliberately: the pump runs for the process's life and
/// there is no join, so nothing would ever reclaim it. The pointer is the
/// thread's argument.
fn spawn_pump<T: Pump>(ctx: T) -> Result<(), &'static str> {
    let entry = T::ENTRY;
    let stack = unsafe { t_burrow_attach(PUMP_STACK) };
    if stack < 0 {
        return Err("pump stack");
    }
    // AAPCS64 wants the stack TOP 16-aligned; the burrow base is page-aligned
    // and the size is a page multiple, so base + size is too.
    let sp = (stack as u64) + PUMP_STACK;
    let arg = alloc::boxed::Box::into_raw(alloc::boxed::Box::new(ctx)) as u64;
    match unsafe { thread::spawn_raw(entry as *const () as u64, sp, arg, 0) } {
        Ok(_) => Ok(()),
        Err(_) => {
            // The thread never started, so nothing else can reach the Box --
            // reclaim it rather than leaking on the error path.
            drop(unsafe { alloc::boxed::Box::from_raw(arg as *mut T) });
            Err("pump spawn")
        }
    }
}

