struct Parsed {
    post: bool,
    addr: String,
    mountpoint: String,
    aname: String,
    /// None = plain 9P; Some = run npxf's handshake first.
    ///
    /// `Zeroizing` because this is the LONG-LIVED credential: unlike a session
    /// key, its compromise is not bounded by this connection. Every derived key
    /// in npxf.rs already wipes on drop; the token is the one secret that used
    /// to be left to a plain `Vec::drop`, which frees the pages without
    /// touching the bytes.
    token: Option<Zeroizing<Vec<u8>>>,
    /// Optional command to run WITH the mount visible. Empty = park instead.
    cmd: Vec<String>,
}

/// Read a token from a file, dropping ONE trailing newline.
///
/// npxf does the same on its side, and it has to: a token file written by any
/// ordinary editor ends in a newline, and a byte of difference is a different
/// pre-shared key and a handshake that fails with no clue why.
/// The largest token file this will read.
///
/// npxf reads into a `Bytes buf(4096)` and fails when `n == buf.size()`
/// (`read_token_file`, npxf src/npxf_main.cpp), so its largest ACCEPTED token is
/// 4095 bytes -- one less than the buffer, which is easy to read as 4096 and is
/// what the comment here used to claim. The difference is not academic: a
/// 4096-byte token file that haul accepts is refused by `npxf-server` reading
/// the same file through the same function, so the server does not start and the
/// guest sees only a refused connection.
///
/// A file bigger than this is a mistake anyway -- a key ring, a log, the wrong
/// path -- and refusing it beats reading it: an unbounded read on a path the
/// caller chose is a way to turn `-t /dev/zero` into an out-of-memory kill.
const TOKEN_FILE_MAX: usize = 4095;

/// The ENV source's cap is a different number for a different reason, and using
/// the file's here was simply borrowing the wrong constant. npxf's `--token-env`
/// is `getenv` + `strlen` with no cap at all, so parity is bounded not by npxf
/// but by the kernel: `ENV_VALUE_MAX` (4096) is the most a variable can hold, so
/// anything at or under it is a value npxf would have accepted.
const TOKEN_ENV_MAX: usize = 4096;

/// Read the token named by an environment variable WITHOUT going through
/// `env::var`.
///
/// `env::var` reads into a 4096-byte STACK ARRAY and copies the value out into a
/// String, leaving the array unwiped when it returns (`libthyla-rs/src/env.rs`).
/// So the token -- the long-lived credential, whose compromise is not bounded by
/// the session the way a derived key's is -- would sit in a dead stack frame for
/// the life of the process, which in the park form is the life of the machine.
/// Wrapping the RESULT in `Zeroizing` wipes the heap copy and says nothing about
/// the one left behind.
///
/// `/env/<NAME>` is a plain file on the per-Proc env device, so reading it here
/// costs nothing and removes that stack copy. It does NOT make `--token-env` a
/// wiped path, and the difference matters: the authoritative bytes live in the
/// kernel's Env entry for the life of the Proc, untouched by our `drop`, and
/// `env_clone_into` hands them to every child the command form spawns. npxf's
/// `getenv` has exactly the same exposure, so this is parity rather than a
/// weaker posture -- but `-t` remains the source to reach for when the token
/// must not outlive its use. The name guard mirrors `env::var`'s.
fn read_token_env(name: &str) -> Result<Zeroizing<Vec<u8>>, &'static str> {
    if name.is_empty() || name.contains('/') {
        return Err("that is not an environment variable name");
    }
    let mut path = String::from("/env/");
    path.push_str(name);
    // NOT trimmed, matching npxf: a variable holds exactly what someone set it
    // to, whereas a file conventionally ends with a newline nobody typed. See
    // npxf::trim_token_file.
    read_token_bytes(&path, TokenRead {
        trim: false,
        max: TOKEN_ENV_MAX,
        // /env is per-Proc and synthetic: devenv reports a FIXED `T_S_IFREG |
        // 0644` for every variable (kernel/devenv.c), and nothing consults it --
        // devenv_wstat is `return -1`, so `chmod 600` cannot even succeed. The
        // mode warning would therefore fire on EVERY --token-env run, saying
        // something false and prescribing something impossible. A warning that
        // always fires is a warning an operator learns to ignore, and this is
        // the only place haul warns about credential exposure at all -- so
        // leaving it on here would cost the warning its meaning on the -t path,
        // where the bits are real.
        warn_mode: false,
        open_msg: "that environment variable is not set",
        read_msg: "cannot read that environment variable",
        large_msg: "that environment variable is too large",
        empty_msg: "that environment variable is empty",
    })
}

fn read_token_file(path: &str) -> Result<Zeroizing<Vec<u8>>, &'static str> {
    read_token_bytes(path, TokenRead {
        trim: true,
        max: TOKEN_FILE_MAX,
        warn_mode: true,
        open_msg: "cannot open the token file",
        read_msg: "cannot read the token file",
        large_msg: "the token file is too large",
        empty_msg: "the token file is empty",
    })
}

/// Every message names the SOURCE the caller actually used. Half of these were
/// once hardcoded to the file wording, so a `--token-env` failure sent the
/// reader looking for a file that was never involved.
struct TokenRead {
    trim: bool,
    max: usize,
    warn_mode: bool,
    open_msg: &'static str,
    read_msg: &'static str,
    large_msg: &'static str,
    empty_msg: &'static str,
}

fn read_token_bytes(path: &str, m: TokenRead) -> Result<Zeroizing<Vec<u8>>, &'static str> {
    let mut f = libthyla_rs::fs::File::open(path).map_err(|_| m.open_msg)?;
    // Warn, as npxf does, rather than refuse: the operator may have a reason,
    // and a mount that fails on a permission bit is worse than one that says so.
    // The token is a long-lived credential shared with the far end, and a
    // world-readable one is shared with everyone on this machine too.
    if m.warn_mode {
        if let Ok(md) = f.metadata() {
            let other = md.permissions() & 0o077;
            if other != 0 {
                say!(
                    "haul: warning: {} is readable beyond its owner (mode {:04o}) -- chmod 600 it",
                    path,
                    md.permissions() & 0o7777
                );
            }
        }
    }
    // Read into a fixed buffer rather than read_to_end + a length check: the
    // check has to come after the allocation, so `-t /dev/zero` would already
    // have consumed the heap by the time it fired. One byte over the cap is
    // enough to detect the overflow without ever holding more than the cap.
    //
    // `Zeroizing` FROM THE ALLOCATION, not wrapped on the way out. Wrapping
    // only the result wiped the success path and left the read-error and
    // too-large returns dropping a plain Vec -- a partial token, or the first
    // 4 KiB of whatever `-t` was mistakenly pointed at, freed unwiped (pages are
    // zeroed on allocation here, not on free). Owning the wipe from the start
    // covers every return, including ones added later. It also covers the
    // bytes `truncate` and the trim leave in spare capacity: zeroize's Vec impl
    // wipes the whole capacity, and this buffer is never reallocated.
    let mut buf: Zeroizing<Vec<u8>> = Zeroizing::new(alloc::vec![0u8; m.max + 1]);
    let mut n = 0usize;
    while n < buf.len() {
        match f.read(&mut buf[n..]) {
            Ok(0) => break,
            Ok(got) => n += got,
            Err(_) => return Err(m.read_msg),
        }
    }
    if n > m.max {
        return Err(m.large_msg);
    }
    buf.truncate(n);
    // npxf::trim_token_file, not an inline pop: the exact bytes trimmed decide
    // the PSK, so the rule lives in one documented place with a test on each
    // side of the wire.
    if m.trim {
        npxf::trim_token_file(&mut buf);
    }
    if buf.is_empty() {
        return Err(m.empty_msg);
    }
    Ok(buf)
}

fn parse_args(args: Args) -> Result<Parsed, &'static str> {
    // Collect argv as &str up front so the grammar itself can be a pure
    // function over strings -- haul::cmdline::plan, which is where the option/
    // operand boundary is decided AND tested. Only the two token SOURCES need
    // syscalls, and they are resolved after the grammar has spoken.
    let mut argv: Vec<&str> = Vec::new();
    let mut i = 1usize; // argv[0] is the program name
    while args.get(i).is_some() {
        match args.get_str(i) {
            Some(v) => argv.push(v),
            None => return Err("argument is not UTF-8"),
        }
        i += 1;
    }

    let plan = match cmdline::plan(&argv) {
        Ok(p) => p,
        Err(cmdline::Bad::WantsUsage) => {
            tell(USAGE);
            return Err("");
        }
        Err(cmdline::Bad::MissingValue(m)) => return Err(m),
        Err(cmdline::Bad::UnknownOption) => return Err("unknown option"),
        Err(cmdline::Bad::InvalidPost) => return Err("post mode wants NAME HOST!PORT; NAME is one /srv component (1..32 bytes); no command or -a (give aname to mount)"),
        Err(cmdline::Bad::DashAfterOperands) => {
            return Err("an option must come before the address; to run a command whose name \
                        starts with a dash, put -- after the mountpoint")
        }
    };

    if plan.verbose {
        VERBOSE.store(1, Ordering::Relaxed);
    }
    let token = match &plan.token {
        Some(cmdline::TokenSource::File(path)) => Some(read_token_file(path)?),
        Some(cmdline::TokenSource::Env(name)) => Some(read_token_env(name)?),
        None => None,
    };

    Ok(Parsed {
        post: plan.post,
        addr: plan.addr,
        mountpoint: plan.mountpoint,
        aname: plan.aname,
        token,
        cmd: plan.cmd,
    })
}

/// Run npxf's three flights on the connected socket and return the live
/// channel.
///
/// FAILS CLOSED ON THE CSPRNG. The ephemeral scalar is the whole of the
/// session's forward secrecy; there is no weaker source to fall back to, so a
/// kernel that will not give us entropy ends the mount here rather than
/// producing a channel that merely looks encrypted.
fn npxf_handshake(fd: i64, ready: Ready, token: &[u8]) -> Result<npxf::Session, &'static str> {
    let mut eph = [0u8; 32];
    let got = libthyla_rs::rand::fill_bytes(&mut eph);
    if got.is_err() {
        return Err("no CSPRNG (needs CAP_CSPRNG_READ) -- refusing to handshake");
    }
    step!("entropy for the ephemeral: ok");

    // Wipe BEFORE the `?`. `Client::start` takes the scalar by value, so our copy
    // is dead either way -- but an early return would have skipped the wipe and
    // left 32 bytes of ephemeral on the stack. Unreachable today (the only
    // failure is EmptyToken, which both token sources already refuse upstream),
    // and unreachable is exactly the condition under which this rots.
    let started = npxf::Client::start(token, eph);
    eph.zeroize();
    let (client, msg1) = started.map_err(|_| "the token is empty")?;

    if !write_exact(fd, ready, &msg1) {
        return Err("handshake: the connection closed while sending our opening flight");
    }
    step!("sent flight 1 ({} bytes)", msg1.len());

    let mut msg2 = [0u8; npxf::MSG2_LEN];
    if !read_exact_before(fd, ready, &mut msg2, HANDSHAKE_MS) {
        return Err("handshake: no reply from the server (wrong token, not npxf, or unreachable)");
    }
    step!("got flight 2 ({} bytes)", msg2.len());

    let (mut session, msg3) = client.finish(&msg2).map_err(|e| match e {
        npxf::Error::ServerAuth => {
            "handshake: server authentication failed -- token mismatch, or intercepted"
        }
        npxf::Error::SmallOrderKey => "handshake: the server sent a small-order public key",
        _ => "handshake: refused",
    })?;

    if !write_exact(fd, ready, &msg3) {
        return Err("handshake: the connection closed while confirming");
    }
    step!("server authenticated, channel up");

    // Hold both directions to the same ceiling the plain path uses, so a server
    // cannot make us allocate npxf's full 8 MiB record just by claiming it.
    session.send.set_max_payload(MSG_MAX as usize);
    session.recv.set_max_payload(MSG_MAX as usize);
    Ok(session)
}

// Creation is the kernel capability gate. A failed post never dials the peer.
fn post_listener(name: &str) -> Result<i64, &'static str> {
    use libthyla_rs::{t_open, t_walk_create, T_WALK_OPEN_FROM_ROOT, T_OPATH,
                     T_OREAD, T_WALK_CREATE_DMSRVBYTE, T_WALK_CREATE_DMSRVCAPE};
    let srv = unsafe { t_open(T_WALK_OPEN_FROM_ROOT, b"/srv".as_ptr(), 4, T_OPATH) };
    if srv < 0 { return Err("cannot open /srv"); }
    let listener = unsafe { t_walk_create(srv, name.as_ptr(), name.len(), T_OREAD,
                                          T_WALK_CREATE_DMSRVBYTE | T_WALK_CREATE_DMSRVCAPE) };
    let _ = unsafe { t_close(srv) };
    if listener < 0 { return Err("cannot post service (requires imperium post, an unused name and a free service slot)"); }
    Ok(listener)
}

fn accept_owner(listener: i64) -> Result<i64, &'static str> {
    let uid = unsafe { libthyla_rs::t_getuid() };
    if uid < 0 { return Err("cannot identify service owner"); }
    loop {
        let conn = unsafe { libthyla_rs::t_srv_accept(listener) };
        if conn < 0 { return Err("accept"); }
        let mut peer = libthyla_rs::TSrvPeerInfo::default();
        let rc = unsafe { libthyla_rs::t_srv_peer(conn, &mut peer) };
        if rc == 0 && peer.alive != 0 && peer.principal_id as i64 == uid {
            return Ok(conn);
        }
        let _ = unsafe { t_close(conn) };
    }
}

/// How long a dial may take before haul says it is still out. A refusal answers
/// in milliseconds; past this the host is slow, down, or behind something that
/// drops the call, and silence until netd gives up would read as a hang.
const SLOW_DIAL: Duration = Duration::from_secs(2);

/// Dial `addr`, saying so while a slow answer is still out, and naming the
/// reason when there is none. `shown` is the address as the operator wrote it.
fn dial(addr: SocketAddrV4, shown: &str) -> Result<TcpStream, String> {
    let unreachable = |e: Error| -> String {
        match e {
            Error::ConnectionRefused => alloc::format!("cannot reach {}: connection refused", shown),
            Error::TimedOut => alloc::format!("cannot reach {}: no answer (timed out)", shown),
            Error::NotFound => alloc::format!("cannot dial {}: no network (/net/tcp is not there)", shown),
            e => alloc::format!("cannot reach {}: {}", shown, e),
        }
    };
    let mut dialing = TcpStream::dial(addr).map_err(unreachable)?;
    if !dialing.wait(SLOW_DIAL).map_err(unreachable)? {
        say!("haul: no answer from {} yet -- still trying", shown);
    }
    dialing.finish().map_err(unreachable)
}

fn run(argv: Args) -> Result<(), String> {
    let mut args = parse_args(argv)?;

    // THE COMMAND FORM REFUSES TO START WITHOUT STDIO, before it opens anything.
    // The kernel hands out the LOWEST free fd, so with slots 0-2 empty the
    // connection's own fds -- ctl, data, ready, and then the pipes -- would
    // land in them, and the command inherits exactly slots 0-2 as its stdio
    // (`Command::spawn`, `Stdio::Inherit`). Its output would go INTO the
    // connection, or into the kernel's reply pipe, where it also defeats
    // `finish_down`: that close would no longer drop the last reference.
    // `fd_devclass` is None for a closed slot, and also for a non-Spoor handle
    // there, which `Command::spawn` would refuse anyway.
    //
    // The park form spawns nothing, so empty stdio is harmless there -- and a
    // daemon-style launcher, the one that produces it, runs the park form. So
    // only the command form is refused.
    if !args.cmd.is_empty() && (0..3).any(|fd| libthyla_rs::fd_devclass(fd).is_none()) {
        return Err("the command form needs stdin, stdout and stderr open (the command would otherwise inherit the connection)".into());
    }

    let listener = if args.post { Some(post_listener(&args.mountpoint)?) } else { None };
    let (host, port) = haul::addr::split_dial(&args.addr)
        .ok_or("address needs a host and a port (host!port, or host:port)")?;
    let ip = Ipv4Addr::parse(host).map_err(|_| "the host is not a dotted-quad IPv4 address")?;
    let port = haul::addr::parse_port(port).ok_or("the port must be 1..=65535")?;
    let addr = SocketAddrV4::new(ip, port);
    step!("dialing {}", addr);
    let stream = dial(addr, &args.addr)?;
    step!("connected");
    // The connection's READINESS fd, opened while the stream still exists to
    // name it. This is `/net/tcp/N/ready`, the QTPOLL sibling -- the only file
    // of the pair that carries readiness at all, and therefore the only one a
    // POLLOUT wait may be pointed at. Its own doc comment describes exactly this
    // use: "a bulk sender polls POLLOUT before retrying a write that returned 0".
    let ready_file = stream.ready_fd().map_err(|_| "cannot open the connection's ready file")?;
    let tcp_ready = Ready(ready_file.as_raw_fd() as i64);
    core::mem::forget(ready_file);

    // The pumps outlive this scope and address the connection by fd, so the
    // TcpStream must NOT drop (its Drop closes ctl + data, tearing the
    // connection down under them). Leaked deliberately: haul lives for the
    // mount's lifetime, so the connection's lifetime IS the process's. The
    // ready fd above is leaked for the same reason and in the same breath.
    let tcp_fd = stream.as_raw_fd() as i64;
    core::mem::forget(stream);

    // THE HANDSHAKE RUNS BEFORE THE PUMPS, and it must: it is a strictly
    // ordered three-flight exchange on the raw socket, so a pump concurrently
    // reading that socket would steal the server's reply. Once it returns, the
    // socket carries records only, and the pumps own it.
    // The handshake is the last thing that needs the token, so it leaves with
    // the handshake -- taken out of `args` and dropped (which wipes it) before
    // the mount goes up. Holding it would mean holding it for the LIFE of the
    // mount, and the park form's life is the machine's.
    let encrypted = args.token.is_some();
    let token = args.token.take();
    let handshake = match token.as_deref() {
        Some(t) => npxf_handshake(tcp_fd, tcp_ready, t).map(Some),
        // A plain-9P mount reaches the same code with nothing to wipe.
        None => Ok(None),
    };
    drop(token);
    let session = handshake?;
    let (sealer, opener) = match session {
        Some(s) => (Some(s.send), Some(s.recv)),
        None => (None, None),
    };

    if let Some(listener) = listener {
        say!("haul: /srv/{} posted for {} ({})", args.mountpoint, args.addr,
             if encrypted { "npxf encrypted" } else { "PLAIN 9P" });
        let conn = accept_owner(listener)?;
        spawn_pump(UpCtx { src: conn, dst: tcp_fd, dst_ready: tcp_ready, sealer })?;
        spawn_pump(DownCtx { src: tcp_fd, dst: conn, dst_ready: Ready(conn),
                             opener, close_on_finish: false })?;
        say!("haul: /srv/{} serving one mount", args.mountpoint);
        step!("watching the posted connection and listener");
        loop {
            if STOPPED.load(Ordering::Acquire) != STOP_NONE {
                return Err("posted connection ended".into());
            }
            // The remote 9P session belongs to the first client. Never splice
            // a second client's tags/fids into it; close queued clients promptly.
            if wait_ready(Ready(listener), libthyla_rs::T_POLLIN, 50) {
                step!("refusing an additional mount");
                let extra = unsafe { libthyla_rs::t_srv_accept(listener) };
                if extra >= 0 { let _ = unsafe { t_close(extra) }; step!("additional mount closed"); }
            }
        }
    }

    // Two half-duplex pipes: c2s carries T-messages, s2c carries R-messages.
    let (c2s_rd, c2s_wr) = unsafe { t_pipe() };
    let (s2c_rd, s2c_wr) = unsafe { t_pipe() };
    if c2s_rd < 0 || c2s_wr < 0 || s2c_rd < 0 || s2c_wr < 0 {
        return Err("pipe pair".into());
    }

    // BOTH PUMPS BEFORE THE ATTACH. SYS_ATTACH_9P drives Tversion + Tattach
    // synchronously; with no pump running, the kernel would wait for an
    // Rversion nothing can deliver and the mount would hang rather than fail.
    spawn_pump(UpCtx {
        src: c2s_rd,
        dst: tcp_fd,
        dst_ready: tcp_ready,
        sealer,
    })?;
    spawn_pump(DownCtx {
        src: tcp_fd,
        dst: s2c_wr,
        // A pipe's own fd carries real POLLOUT, so it is its own readiness.
        dst_ready: Ready(s2c_wr),
        opener,
        close_on_finish: true,
    })?;
    step!("pumps up; attaching (Tversion + Tattach run inside the syscall)");

    // The attach takes its own refs on both transport Spoors, so our copies of
    // the CLIENT ends close immediately after -- the session keeps the channel,
    // not these fds. (The SERVER ends stay open: they are the pumps'.)
    let root = unsafe {
        t_attach_9p(
            c2s_wr,
            s2c_rd,
            args.aname.as_ptr(),
            args.aname.len(),
            0,
            T_ATTACH_9P_CAPE,
        )
    };
    let _ = unsafe { t_close(c2s_wr) };
    let _ = unsafe { t_close(s2c_rd) };
    if root < 0 {
        // The pumps have the diagnosis: a server that hung up mid-handshake
        // stops one of them, and which one says whether we failed to send or
        // failed to hear back.
        return Err(String::from(match STOPPED.load(Ordering::Acquire) {
            STOP_UP => "attach (the connection closed while sending)",
            STOP_DOWN => "attach (the server closed without replying)",
            _ => "attach (9P handshake refused)",
        }));
    }

    step!("attached; mounting at {}", args.mountpoint);
    let rc = unsafe {
        t_mount(
            args.mountpoint.as_ptr(),
            args.mountpoint.len(),
            root,
            T_MREPL,
        )
    };
    let _ = unsafe { t_close(root) };
    if rc < 0 {
        return Err("mount".into());
    }

    // Under -v, prove the mount from INSIDE this Proc before anyone else tries
    // to use it. A successful t_mount says the entry went into our table; it
    // does not say a walk crosses into the remote tree. Listing here separates
    // "the mount is wrong" from "the caller cannot see it", which are the two
    // failures that otherwise both present as `no such file or namespace entry`.
    //
    // Like the attach, this is a synchronous 9P round trip with no deadline, and
    // a peer that hangs up during it ends it the same way: the down pump closes
    // `s2c_wr` as it dies (`finish_down`), the kernel reads EOF, and read_dir
    // fails instead of blocking. The STOPPED check therefore only skips a listing
    // already known to be doomed -- and after a failure it separates "the
    // connection ended mid-listing" from "the mount did not take", which would
    // otherwise print the same line.
    if VERBOSE.load(Ordering::Relaxed) != 0 && STOPPED.load(Ordering::Acquire) == STOP_NONE {
        step!("mount check: listing {} ...", args.mountpoint);
        match libthyla_rs::fs::read_dir(args.mountpoint.as_str()) {
            Ok(rd) => {
                let mut n = 0usize;
                let mut first = String::new();
                for e in rd.flatten() {
                    if n == 0 {
                        first = String::from(e.file_name());
                    }
                    n += 1;
                }
                step!("mount check: {} entr(y/ies) here, first {:?}", n, first);
            }
            Err(_) if STOPPED.load(Ordering::Acquire) != STOP_NONE => {
                step!("mount check: the connection ended during the listing")
            }
            Err(_) => step!("mount check: CANNOT read {} -- the mount did not take", args.mountpoint),
        }
    }

    // Name the channel, always. Which mode is live is exactly the thing a
    // reader must never have to infer from the absence of a flag.
    say!(
        "haul: {} mounted at {} (aname {}, {})",
        args.addr,
        args.mountpoint,
        args.aname,
        if encrypted {
            "npxf encrypted"
        } else {
            "PLAIN 9P"
        }
    );

    // WITH A COMMAND: run it here, where the mount exists.
    //
    // A mount lands in the CALLING Proc's Territory and nowhere else (I-1), so
    // `haul ... &` from a shell mounts into haul's OWN namespace and the shell
    // sees nothing. That much is measured and settled:
    //   cat: /home/cora/host/hello.txt: no such file or namespace entry
    // while haul sat happily mounted, its own read_dir of the mountpoint
    // returning the five entries the server exports.
    //
    // The Plan 9 answer to that is rfork-mount-exec, which is this form: the
    // child is downstream of the mount rather than beside it, so it sees the
    // tree -- rfork_internal clones the mount table unconditionally, and spawn
    // reaches it through rfork_with_caps(RFPROC, ..). haul-npxf asserts it end
    // to end: the child reads a file through the mount.
    //
    // A server without the fused Twalkgetattr (npxf is one) makes this look
    // broken in a specific way worth recognising: the child can LIST the mount
    // point, but anything BENEATH it is "no such file or namespace entry". That
    // was dev9p taking the server's EOPNOTSUPP for a failed walk instead of a
    // missing operation to fall back from. Spawn was never involved.
    //
    // What no form of this can do is hand the mount to an EXISTING shell: a
    // child never reaches into its parent's namespace (docs/HAUL-DESIGN.md 4.3).
    if !args.cmd.is_empty() {
        let mut c = libthyla_rs::process::Command::new(args.cmd[0].clone());
        c.args(args.cmd[1..].iter().cloned());
        let mut child = c.spawn().map_err(|_| "could not run the command")?;
        // Poll the child AND the transport, rather than blocking in wait().
        //
        // A blocking wait watches only the child, and the child is not the only
        // thing that can end. If a pump stops mid-session, nobody drains the
        // pipes, so every filesystem call the child makes into this mount blocks
        // forever -- and a wait that is watching only the child then waits
        // forever too, with the process holding a mount that cannot serve. The
        // park form below already handles exactly this in under 200 ms; the
        // command form had no bound at all.
        let status = loop {
            match child.try_wait() {
                Ok(Some(st)) => break st,
                Err(_) => return Err("waiting for the command".into()),
                Ok(None) => {}
            }
            if STOPPED.load(Ordering::Acquire) != STOP_NONE {
                say!(
                    "haul: {} closed the connection while the command was running",
                    args.addr
                );
                return Err("the connection ended under the command".into());
            }
            let _ = libthyla_rs::time::sleep(libthyla_rs::time::Duration::from_millis(50));
        };
        // The transport dies with us, which is correct: the command has run, so
        // the tree it needed is no longer needed.
        return if status.success() {
            Ok(())
        } else {
            Err("the command exited non-zero".into())
        };
    }

    // WITHOUT ONE: the mount lives exactly as long as this Proc does -- the
    // pumps ARE the transport, so exiting would tear the session down under
    // whoever is walking the tree. Park until a pump reports the channel ended.
    loop {
        if STOPPED.load(Ordering::Acquire) != STOP_NONE {
            say!("haul: {} closed the connection -- the mount is dead", args.addr);
            // NOT Ok(()). A supervisor that restarts on a non-zero exit would
            // read success for a mount that is gone, and the command form's twin
            // above already returns Err for the same event.
            return Err("the peer closed the connection".into());
        }
        let _ = libthyla_rs::time::sleep(libthyla_rs::time::Duration::from_millis(200));
    }
}

#[no_mangle]
pub extern "C" fn rs_main() -> i64 {
    // First, before anything opens a file (see STDERR_LIVE).
    STDERR_LIVE.store(libthyla_rs::fd_devclass(2).is_some(), Ordering::Relaxed);
    match run(env::args()) {
        Ok(()) => 0,
        // The empty reason is --help / usage: already printed, and a second
        // line naming it as a failure would be wrong.
        Err(why) if why.is_empty() => 2,
        Err(why) => {
            say!("haul: {}", why);
            1
        }
    }
}
